# Auto-generated compliance files that always overwrite silently (PUB-05).
# These are NOT protected by _check_overwrite_protection: README.md, LICENSE,
# codebook.md, and every codebooks/**/*.md path.
_AUTO_GENERATED: frozenset[str] = frozenset({"readme.md", "license", "codebook.md"})
_AUTO_GENERATED_PREFIXES: tuple[str, ...] = ("codebooks/",)


def _is_auto_generated(remote: str) -> bool:
    """Return ``True`` when *remote* is an auto-generated compliance file.

    Auto-generated files — ``README.md``, ``LICENSE``, ``codebook.md`` and
    ``codebooks/**/*.md`` — always overwrite the remote without prompting
    (PUB-05).  Matching is case-insensitive, and ``codebooks/`` is a prefix
    match so every per-file codebook page is covered.

    Args:
        remote: Remote path in the repository (POSIX separators).

    Returns:
        ``True`` when the file is regenerated by ``prepare`` and should
        never be protected by overwrite protection.
    """
    lower = remote.lower()
    return lower in _AUTO_GENERATED or lower.startswith(_AUTO_GENERATED_PREFIXES)


